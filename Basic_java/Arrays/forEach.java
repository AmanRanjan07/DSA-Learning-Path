package DsaInJava.Basic_java.Arrays;
// Array's are mutable in Java so that we can change in this...
// String is immutable so that we cann't change in this ..
public class forEach {
    public static void main(String[] args) {
        double[] mylist = {1.9,2.9,3.4,3.6};
        for(double ele : mylist){
            System.out.println(ele);  // using for each loop you will get the array of the list
        }
    }
}


